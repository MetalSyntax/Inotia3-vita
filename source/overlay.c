// Batched quads: one glDrawArrays per color instead of one per pixel.
// static: vitaGL may read client arrays after the call returns.
#define OV_MAX_QUADS 2048
static GLfloat ov_verts[OV_MAX_QUADS * 12];
static GLfloat ov_uvs[OV_MAX_QUADS * 12]; // all zero: the white 1x1 texture samples white anywhere
static int ov_n = 0;

static void ov_quad(float x0, float y0, float x1, float y1) {
    if (ov_n >= OV_MAX_QUADS) return;
    GLfloat *v = &ov_verts[ov_n++ * 12];
    v[0] = x0; v[1] = y0; v[2] = x1; v[3]  = y0; v[4]  = x1; v[5]  = y1;
    v[6] = x0; v[7] = y0; v[8] = x1; v[9]  = y1; v[10] = x0; v[11] = y1;
}

static void ov_flush(uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (!ov_n) return;
    glColor4ub(r, g, b, a);
    glVertexPointer(2, GL_FLOAT, 0, ov_verts);
    glTexCoordPointer(2, GL_FLOAT, 0, ov_uvs);
    glDrawArrays(GL_TRIANGLES, 0, ov_n * 6);
    ov_n = 0;
}

static GLboolean s_tex0, s_tex1, s_tc0, s_tc1, s_carr, s_blend, s_cull, s_depth, s_scissor, s_alpha;

// The game leaves arbitrary state behind (scissor, texture unit 1's mask,
// translated modelview...): save it, draw like SGL_grpFillRect's hook does
// (unit 0 + white texture, patch.c), and restore everything in overlay_end().
void overlay_begin(void) {
    glActiveTexture(GL_TEXTURE1);
    glClientActiveTexture(GL_TEXTURE1);
    s_tex1 = glIsEnabled(GL_TEXTURE_2D);
    s_tc1 = glIsEnabled(GL_TEXTURE_COORD_ARRAY);
    glDisable(GL_TEXTURE_2D);
    glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    glActiveTexture(GL_TEXTURE0);
    glClientActiveTexture(GL_TEXTURE0);
    s_tex0 = glIsEnabled(GL_TEXTURE_2D);
    s_tc0 = glIsEnabled(GL_TEXTURE_COORD_ARRAY);
    s_carr = glIsEnabled(GL_COLOR_ARRAY);
    s_blend = glIsEnabled(GL_BLEND);
    s_cull = glIsEnabled(GL_CULL_FACE);
    s_depth = glIsEnabled(GL_DEPTH_TEST);
    s_scissor = glIsEnabled(GL_SCISSOR_TEST);
    s_alpha = glIsEnabled(GL_ALPHA_TEST);

    glDisable(GL_CULL_FACE);
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_SCISSOR_TEST);
    glDisable(GL_ALPHA_TEST);
    glDisableClientState(GL_COLOR_ARRAY);
    glEnableClientState(GL_VERTEX_ARRAY);
    glEnableClientState(GL_TEXTURE_COORD_ARRAY);
    glEnable(GL_TEXTURE_2D);
    glBindTexture(GL_TEXTURE_2D, gl_get_white_texture());
    glTexEnvf(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrthof(0.0f, 960.0f, 544.0f, 0.0f, -1.0f, 1.0f);
    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();
}

void overlay_end(void) {
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glMatrixMode(GL_MODELVIEW);
    glPopMatrix();
    glColor4f(1.0f, 1.0f, 1.0f, 1.0f);
    if (!s_tex0) glDisable(GL_TEXTURE_2D);
    if (!s_tc0) glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    if (s_carr) glEnableClientState(GL_COLOR_ARRAY);
    if (!s_blend) glDisable(GL_BLEND);
    if (s_cull) glEnable(GL_CULL_FACE);
    if (s_depth) glEnable(GL_DEPTH_TEST);
    if (s_scissor) glEnable(GL_SCISSOR_TEST);
    if (s_alpha) glEnable(GL_ALPHA_TEST);
    glActiveTexture(GL_TEXTURE1);
    glClientActiveTexture(GL_TEXTURE1);
    if (s_tex1) glEnable(GL_TEXTURE_2D);
    if (s_tc1) glEnableClientState(GL_TEXTURE_COORD_ARRAY);
    glActiveTexture(GL_TEXTURE0);
    glClientActiveTexture(GL_TEXTURE0);
}

// Carnivores-vita style corner brackets: arms 25% of the side capped at 20px,
// dark teal outline (#0E3A40) under an Inotia HUD cyan core (#5FF0FF).
void overlay_brackets(float x0, float y0, float x1, float y1) {
    float lx = (x1 - x0) * 0.25f, ly = (y1 - y0) * 0.25f;
    if (lx > 20.0f) lx = 20.0f;
    if (ly > 20.0f) ly = 20.0f;
    for (int p = 0; p < 2; p++) {
        float t = 3.0f, g = p == 0 ? 2.0f : 0.0f;
        const float r[8][4] = {
            { x0 - t, y0 - t, x0 + lx, y0 }, { x0 - t, y0, x0, y0 + ly },
            { x1 - lx, y0 - t, x1 + t, y0 }, { x1, y0, x1 + t, y0 + ly },
            { x0 - t, y1, x0 + lx, y1 + t }, { x0 - t, y1 - ly, x0, y1 },
            { x1 - lx, y1, x1 + t, y1 + t }, { x1, y1 - ly, x1 + t, y1 },
        };
        for (int i = 0; i < 8; i++) ov_quad(r[i][0] - g, r[i][1] - g, r[i][2] + g, r[i][3] + g);
        if (p == 0) ov_flush(0x0e, 0x3a, 0x40, 204);
        else        ov_flush(0x5f, 0xf0, 0xff, 230);
    }
}

static char s_osd_msg[64];
static uint64_t s_osd_until = 0;
#define OSD_MS 2000
#define OSD_FADE_MS 300

void osd_show(const char *msg) {
    strncpy(s_osd_msg, msg, sizeof(s_osd_msg) - 1);
    s_osd_msg[sizeof(s_osd_msg) - 1] = '\0';
    s_osd_until = current_timestamp_ms() + OSD_MS;
}

void osd_draw(void) {
    uint64_t now = current_timestamp_ms();
    if (now >= s_osd_until) return;
    uint64_t left = s_osd_until - now;
    uint8_t alpha = left < OSD_FADE_MS ? (uint8_t) (left * 240 / OSD_FADE_MS) : 240;

    const float scale = 2.0f;
    float box_w = strlen(s_osd_msg) * 8.0f * scale + 36.0f, box_h = 44.0f;
    float box_x = (960.0f - box_w) / 2.0f, box_y = 22.0f;

    overlay_begin();
    ov_quad(box_x, box_y, box_x + box_w, box_y + box_h);
    ov_flush(12, 16, 26, alpha);
    ov_quad(box_x, box_y + box_h - 3.0f, box_x + box_w, box_y + box_h);
    ov_flush(40, 170, 255, alpha);
    ov_quad(box_x, box_y, box_x + box_w, box_y + 2.0f);
    ov_flush(40, 170, 255, (uint8_t) (alpha * 0.7f));
    float x = box_x + 18.0f, y = box_y + 14.0f;
    for (const char *s = s_osd_msg; *s; s++, x += 8.0f * scale) {
        unsigned char c = (unsigned char) *s;
        if (c < 32 || c > 127) c = '?';
        for (int row = 0; row < 8; row++)
            for (int col = 0; col < 8; col++)
                if ((font8x8_basic[c - 32][row] >> (7 - col)) & 1)
                    ov_quad(x + col * scale, y + row * scale, x + (col + 1) * scale, y + (row + 1) * scale);
    }
    ov_flush(240, 245, 255, alpha);
    overlay_end();
}
